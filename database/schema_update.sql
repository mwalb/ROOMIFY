-- Add foreign key constraint if it doesn't exist
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_room_property') THEN
        ALTER TABLE rooms ADD CONSTRAINT fk_room_property FOREIGN KEY (property_id) REFERENCES properties(id);
    END IF;
END $$;

-- User Favorites Table
CREATE TABLE IF NOT EXISTS user_favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_room UNIQUE (user_id, room_id)
);

-- Payments Table
CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT,
    room_id BIGINT,
    user_id BIGINT,
    owner_id BIGINT,
    amount DOUBLE PRECISION NOT NULL,
    provider VARCHAR(255) DEFAULT 'M-PESA',
    phone VARCHAR(255),
    reference_number VARCHAR(255),
    status VARCHAR(255) DEFAULT 'SUCCESS',
    message TEXT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- In-App Notifications Table
CREATE TABLE IF NOT EXISTS in_app_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    type VARCHAR(100) DEFAULT 'SYSTEM',
    reference_id BIGINT,
    is_read BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

